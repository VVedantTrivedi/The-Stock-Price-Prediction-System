def predict_for_gradio(
    index_name,
    company_selection,
    selected_date
):
    """
    Predicts the stock price for a selected
    company and future trading date.
    """

    # Validate index
    if index_name not in INDEX_STOCKS:
        return "Please select a valid index."

    # Extract ticker
    ticker = extract_ticker(
        company_selection
    )

    # Validate company
    if ticker is None:
        return "Please select a company."

    # Validate date
    if not selected_date:
        return "Please select a forecast date."

    # Extract actual date
    date_string = selected_date.split(" ")[0]

    selected_date_value = pd.to_datetime(
        date_string
    )

    # Generate forecast
    forecast_df = forecast_next_days(
        ticker=ticker,
        days=5,
        period="5y"
    )

    # Find selected date
    selected_row = forecast_df[
        forecast_df["Date"] == selected_date_value
    ]

    # Validate date availability
    if selected_row.empty:
        return "Selected date is not available."

    # Extract prediction
    predicted_price = selected_row[
        "Predicted_Close"
    ].iloc[0]

    return (
        f"Stock: {company_selection}\n"
        f"Index: {index_name}\n"
        f"Forecast Date: "
        f"{selected_date_value.strftime('%Y-%m-%d (%A)')}\n"
        f"Predicted Closing Price: "
        f"₹{predicted_price:.2f}\n \n \n"


    )

