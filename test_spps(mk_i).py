# Preparing Data for Model Training

def prepare_model_data(data):
    """
    Creates the next-day target and separates features from target.
    """

    prepared_data = data.copy()

    # Next day's closing price becomes the prediction target
    prepared_data[TARGET_COLUMN] = prepared_data["Close"].shift(-1)

    # Remove the final row because its next-day price is unavailable
    prepared_data = prepared_data.dropna()

    X = prepared_data[FEATURE_COLUMNS]
    y = prepared_data[TARGET_COLUMN]

    return X, y, prepared_data

# Complete Data Preparation Pipeline

def build_stock_dataset(ticker, period="5y"):
    """
    Downloads and prepares the complete dataset for a selected stock.
    """

    raw_data = download_stock_data(
        ticker=ticker,
        period=period
    )

    feature_data = create_features(raw_data)

    X, y, prepared_data = prepare_model_data(
        feature_data
    )

    return raw_data, prepared_data, X, y

