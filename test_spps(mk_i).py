# Predict Price for a Selected Future Trading Date

def predict_selected_date(
    ticker,
    selected_date,
    period="5y"
):
    """
    Returns the predicted price for a selected
    future trading date.
    """

    # Generate 5-day forecast
    forecast_df = forecast_next_days(
        ticker=ticker,
        days=5,
        period=period
    )

    # Convert selected date to datetime
    selected_date = pd.to_datetime(
        selected_date
    )

    # Find the selected date
    selected_prediction = forecast_df[
        forecast_df["Date"] == selected_date
    ]

    # Validate selected date
    if selected_prediction.empty:

        raise ValueError(
            "Selected date is not available in the forecast."
        )

    # Return the selected prediction
    return selected_prediction.iloc[0]

