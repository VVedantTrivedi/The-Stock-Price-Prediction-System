# Dynamic Historical Stock Data Collection

def download_stock_data(ticker, period="5y"):
    """
    Downloads historical daily stock data for the selected stock.
    """

    stock_data = yf.download(
        ticker,
        period=period,
        interval="1d",
        auto_adjust=False,
        progress=False
    )

    if stock_data.empty:
        raise ValueError(f"No data found for ticker: {ticker}")

    # Convert yfinance MultiIndex columns into simple column names
    if isinstance(stock_data.columns, pd.MultiIndex):
        stock_data.columns = stock_data.columns.get_level_values(0)

    # Keep only the required market columns
    required_columns = ["Open", "High", "Low", "Close", "Volume"]
    stock_data = stock_data[required_columns]

    # Remove missing values
    stock_data = stock_data.dropna()

    return stock_data

# Technical Indicator and Feature Engineering Function

def create_features(stock_data):
    """
    Creates technical indicators and prepares the stock dataset.
    """

    data = stock_data.copy()

    # Moving Averages
    data["SMA10"] = data["Close"].rolling(window=10).mean()
    data["SMA20"] = data["Close"].rolling(window=20).mean()
    data["SMA50"] = data["Close"].rolling(window=50).mean()

    # Exponential Moving Averages
    data["EMA12"] = data["Close"].ewm(
        span=12,
        adjust=False
    ).mean()

    data["EMA26"] = data["Close"].ewm(
        span=26,
        adjust=False
    ).mean()

    # Daily Return
    data["Daily_Return"] = data["Close"].pct_change()

    # RSI
    rsi = RSIIndicator(
        close=data["Close"],
        window=14
    )

    data["RSI"] = rsi.rsi()

    # MACD
    macd = MACD(
        close=data["Close"],
        window_slow=26,
        window_fast=12,
        window_sign=9
    )

    data["MACD"] = macd.macd()
    data["MACD_Signal"] = macd.macd_signal()
    data["MACD_Hist"] = macd.macd_diff()

    # Bollinger Bands
    bollinger = BollingerBands(
        close=data["Close"],
        window=20,
        window_dev=2
    )

    data["BB_High"] = bollinger.bollinger_hband()
    data["BB_Mid"] = bollinger.bollinger_mavg()
    data["BB_Low"] = bollinger.bollinger_lband()

    # Remove rows with incomplete indicators
    data = data.dropna()

    return data

