# Multi-Day Stock Price Forecasting with Actual Trading Dates

def get_next_trading_days(last_date, days=5):
    """
    Generates the next trading days, excluding Saturdays and Sundays.
    """

    next_days = []

    current_date = pd.Timestamp(last_date)

    while len(next_days) < days:

        current_date += pd.Timedelta(days=1)

        # Monday = 0, Sunday = 6
        if current_date.weekday() < 5:
            next_days.append(current_date)

    return next_days


def forecast_next_days(ticker, days=5, period="5y"):
    """
    Generates recursive forecasts mapped to actual future trading dates.
    """

    # Download historical stock data
    raw_data = download_stock_data(
        ticker=ticker,
        period=period
    )

    # Generate future trading dates
    future_dates = get_next_trading_days(
        last_date=raw_data.index[-1],
        days=days
    )

    forecast_results = []

    # Copy historical data for recursive forecasting
    current_data = raw_data.copy()

    for forecast_date in future_dates:

        # Recalculate technical indicators
        updated_features = create_features(
            current_data
        )

        # Select the latest available feature row
        latest_features = updated_features[
            FEATURE_COLUMNS
        ].iloc[[-1]]

        # Generate prediction using the selected best model
        if best_model_name == "Linear Regression":

            predicted_price = linear_model.predict(
                latest_features
            )[0]

        elif best_model_name == "Random Forest":

            predicted_price = random_forest_model.predict(
                latest_features
            )[0]

        elif best_model_name == "XGBoost":

            predicted_price = xgb_model.predict(
                latest_features
            )[0]

        elif best_model_name == "LSTM":

            latest_scaled = scaler.transform(
                latest_features
            )

            latest_lstm = latest_scaled.reshape(
                1,
                1,
                len(FEATURE_COLUMNS)
            )

            predicted_scaled = corrected_lstm_model.predict(
                latest_lstm,
                verbose=0
            )

            predicted_price = target_scaler.inverse_transform(
                predicted_scaled
            )[0][0]

        else:
            raise ValueError(
                "Unknown model selected."
            )

        # Store forecast date and predicted price
        forecast_results.append(
            {
                "Date": forecast_date,
                "Day": forecast_date.strftime("%A"),
                "Predicted_Close": predicted_price
            }
        )

        # Create synthetic next trading-day data
        new_row = pd.DataFrame(
            {
                "Open": [predicted_price],
                "High": [predicted_price],
                "Low": [predicted_price],
                "Close": [predicted_price],
                "Volume": [
                    current_data["Volume"].iloc[-1]
                ]
            },
            index=[forecast_date]
        )

        # Add prediction to data for recursive forecasting
        current_data = pd.concat(
            [
                current_data,
                new_row
            ]
        )

    # Convert results into a DataFrame
    forecast_df = pd.DataFrame(
        forecast_results
    )

    return forecast_df

